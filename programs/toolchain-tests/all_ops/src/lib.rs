        put(_svm512_min_epi32(a, b));
        put(_svm512_max_epu32(a, b));
        put(_svm512_min_epu32(a, b));
        put(_svm512_max_epi16(a, b));
        put(_svm512_min_epi16(a, b));
        put(_svm512_max_epu64(a, b));
        put(_svm512_min_epu64(a, b));
