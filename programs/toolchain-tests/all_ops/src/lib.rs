//! Every intrinsic once, to check that each marker is known to the pass and
//! encodes to its opcode.
//!
//! input: [0, 192) vectors a, b, c; [192, 200) a u64 x (also the mask).
//! output: the k-th vector result at 256 + 64k, then the masked stores, the
//! scatters and the `stn`, then the scalar results as u64.
#![no_std]

